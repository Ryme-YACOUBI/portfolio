(function () {
    let currentLanguage = "en";

    /* Retourne la traduction d'une clé (repli sur l'anglais, puis sur la clé). */
    function t(key, lang) {
        const dictionary = translations[lang || currentLanguage] || translations.en;
        if (key in dictionary) return dictionary[key];
        if (key in translations.en) return translations.en[key];
        return key;
    }

    /* Applique les traductions aux éléments [data-i18n] et [data-i18n-attr] d'une zone. */
    function applyTranslations(root) {
        const scope = root || document;
        const dictionary = translations[currentLanguage];

        scope.querySelectorAll("[data-i18n]").forEach(function (element) {
            const key = element.getAttribute("data-i18n");
            if (key in dictionary) {
                element.textContent = dictionary[key];
            }
        });

        /* data-i18n-attr="aria-label:themeAria;alt:photoAlt" */
        scope.querySelectorAll("[data-i18n-attr]").forEach(function (element) {
            element.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
                const parts = pair.split(":");
                const attribute = (parts[0] || "").trim();
                const key = (parts[1] || "").trim();
                if (attribute && key in dictionary) {
                    element.setAttribute(attribute, dictionary[key]);
                }
            });
        });
    }

    /* Le bouton affiche la langue vers laquelle on bascule. */
    function updateLanguageButton() {
        const languageButton = document.getElementById("btn_lang");
        if (!languageButton) return;

        const target = currentLanguage === "en" ? "fr" : "en";
        languageButton.textContent = target.toUpperCase();
        languageButton.setAttribute("lang", target);
        languageButton.setAttribute(
            "aria-label",
            t(target === "fr" ? "langAriaToFr" : "langAriaToEn")
        );
    }

    function setLanguage(lang) {
        if (!translations[lang]) return;
        currentLanguage = lang;

        document.documentElement.lang = lang;
        applyTranslations(document);
        updateLanguageButton();

        /* Prévient les composants React (voir src/useLanguage.js). */
        document.dispatchEvent(new CustomEvent("i18n:change", { detail: { lang: lang } }));
    }

    function toggleLanguage() {
        setLanguage(currentLanguage === "en" ? "fr" : "en");
    }

    /* API globale utilisable par les modules ES / React. */
    window.i18n = {
        t: t,
        getLanguage: function () { return currentLanguage; },
        setLanguage: setLanguage,
        toggleLanguage: toggleLanguage,
        applyTranslations: applyTranslations,
        translations: translations
    };

    document.addEventListener("DOMContentLoaded", function () {
        const languageButton = document.getElementById("btn_lang");

        if (!languageButton) {
            console.error("Le bouton btn_lang est introuvable.");
            return;
        }

        /* Affichage initial : anglais (le HTML est déjà en anglais). */
        document.documentElement.lang = currentLanguage;
        updateLanguageButton();

        languageButton.addEventListener("click", toggleLanguage);
    });
})();
